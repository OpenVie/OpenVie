package com.cacanode.api.auth.sso;

import lombok.Getter;
import lombok.Setter;
import org.springframework.boot.context.properties.ConfigurationProperties;
import org.springframework.stereotype.Component;

/**
 * Keycloak SSO bridge configuration (dual mode with password login).
 *
 * <p>Keycloak access tokens are exchanged once for internal workspace-scoped
 * credentials and are never accepted as API credentials themselves, so every
 * request keeps flowing through the membership re-resolution in
 * {@code JwtAuthFilter}. Registering as a component keeps password-only
 * deployments untouched: with {@code enabled=false} the exchange endpoint
 * refuses immediately and no Keycloak connection is ever opened (the JWKS
 * decoder is also built lazily on first exchange, so a stopped Keycloak can
 * never break application startup).
 */
@Getter
@Setter
@Component
@ConfigurationProperties(prefix = "sso")
public class SsoProperties {

    /** Master switch; password login always stays available. */
    private boolean enabled = false;

    /** Realm issuer, e.g. http://localhost:18080/realms/openvie. */
    private String issuerUri = "http://localhost:18080/realms/openvie";

    /** Public browser client from the realm export (PKCE flow). */
    private String frontendClientId = "openvie-frontend";

    /** Confidential server-side client from the realm export. */
    private String backendClientId = "openvie-backend";

    /**
     * Confidential client secret. Reserved for future machine-to-machine use;
     * the browser PKCE exchange presents the public frontend client and no
     * secret. Generated by Keycloak on first realm import: read it from the
     * admin console into env. Never committed.
     */
    private String backendClientSecret = "";
}
