package com.openvie.api.bizapp.connector;

import org.eclipse.paho.client.mqttv3.IMqttClient;
import org.eclipse.paho.client.mqttv3.MqttClient;
import org.eclipse.paho.client.mqttv3.MqttException;
import org.springframework.stereotype.Component;

/** Production client factory: one short-lived Paho client per connector job. */
@Component
public class PahoMqttClientFactory implements MqttClientFactory {

    @Override
    public IMqttClient create(String brokerUrl, String clientId) throws MqttException {
        return new MqttClient(brokerUrl, clientId);
    }
}
